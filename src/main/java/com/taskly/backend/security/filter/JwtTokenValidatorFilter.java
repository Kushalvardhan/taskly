
package com.taskly.backend.security.filter;

import com.taskly.backend.constants.ApplicationConstants;
import io.jsonwebtoken.Claims;
import io.jsonwebtoken.ExpiredJwtException;
import io.jsonwebtoken.JwtException;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.security.Keys;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import lombok.RequiredArgsConstructor;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.core.env.Environment;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.authority.AuthorityUtils;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.util.AntPathMatcher;
import org.springframework.web.filter.OncePerRequestFilter;

import javax.crypto.SecretKey;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.List;

@RequiredArgsConstructor
public class JwtTokenValidatorFilter extends OncePerRequestFilter {

    private final AntPathMatcher pathMatcher = new AntPathMatcher();
    private final Environment env;

    @Qualifier("publicPaths")
    private final List<String> publicPaths;

    @Override
    protected void doFilterInternal(
            HttpServletRequest request,
            HttpServletResponse response,
            FilterChain filterChain
    ) throws ServletException, IOException {

        String authHeader =
                request.getHeader(ApplicationConstants.JWT_HEADER);

        // No token: continue. Spring Security will protect secured endpoints.
        if (authHeader == null) {
            filterChain.doFilter(request, response);
            return;
        }

        // Validate the Authorization header format.
        if (!authHeader.startsWith("Bearer ")
                || authHeader.length() <= 7) {
            sendUnauthorized(response, "Invalid Authorization header");
            return;
        }

        try {
            // Remove the "Bearer " prefix.
            String jwt = authHeader.substring(7);

            String secret = env.getProperty(
                    ApplicationConstants.JWT_SECRET_KEY,
                    ApplicationConstants.JWT_SECRET_DEFAULT_VALUE
            );

            SecretKey secretKey = Keys.hmacShaKeyFor(
                    secret.getBytes(StandardCharsets.UTF_8)
            );

            // Verify the signature and automatically check expiration.
            Claims claims = Jwts.parser()
                    .verifyWith(secretKey)
                    .build()
                    .parseSignedClaims(jwt)
                    .getPayload();

            // Read the claims generated by JwtUtil.
            String email = claims.getSubject();
            String roles = claims.get("roles", String.class);

            if (email == null || email.isBlank() || roles == null) {
                sendUnauthorized(response, "Required JWT claims are missing");
                return;
            }

            // Convert the roles claim into Spring Security authorities.
            Authentication authentication =
                    new UsernamePasswordAuthenticationToken(
                            email,
                            null,
                            AuthorityUtils.commaSeparatedStringToAuthorityList(roles)
                    );

            // Store the authenticated user for this request.
            SecurityContextHolder.getContext()
                    .setAuthentication(authentication);

        } catch (ExpiredJwtException exception) {
            sendUnauthorized(response, "Token expired");
            return;

        } catch (JwtException | IllegalArgumentException exception) {
            sendUnauthorized(response, "Invalid token");
            return;
        }

        filterChain.doFilter(request, response);
    }

    private void sendUnauthorized(
            HttpServletResponse response,
            String message
    ) throws IOException {

        SecurityContextHolder.clearContext();
        response.setStatus(HttpServletResponse.SC_UNAUTHORIZED);
        response.setContentType("text/plain");
        response.getWriter().write(message);
    }

    @Override
    protected boolean shouldNotFilter(HttpServletRequest request) {
        String path = request.getRequestURI();

        return publicPaths.stream().anyMatch(publicPath ->
                pathMatcher.match(publicPath, path)
        );
    }
}
