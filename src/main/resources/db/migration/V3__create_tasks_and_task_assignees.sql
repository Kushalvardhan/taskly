
-- ============================================
-- V3: Create tasks table
-- ============================================

CREATE TABLE tasks (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       project_id BIGINT NOT NULL,
                       creator BIGINT NOT NULL,

                       title VARCHAR(255) NOT NULL,
                       description TEXT,

                       start_date TIMESTAMPTZ,
                       deadline TIMESTAMPTZ,

                       type VARCHAR(20) NOT NULL,
                       priority VARCHAR(20) NOT NULL,
                       status VARCHAR(20) NOT NULL,

    -- Audit columns from BaseEntity
                       created_at TIMESTAMPTZ NOT NULL,
                       updated_at TIMESTAMPTZ,
                       created_by VARCHAR(255),
                       updated_by VARCHAR(255),

    -- Foreign keys
                       CONSTRAINT fk_tasks_project
                           FOREIGN KEY (project_id)
                               REFERENCES org_projects(id),

                       CONSTRAINT fk_tasks_creator
                           FOREIGN KEY (creator)
                               REFERENCES users(id)
);


-- ============================================
-- V3: Create task_assignees table
-- ============================================

CREATE TABLE task_assignees (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                task_id BIGINT NOT NULL,
                                user_id BIGINT NOT NULL,

                                status VARCHAR(20) NOT NULL,

    -- Audit columns from BaseEntity
                                created_at TIMESTAMPTZ NOT NULL,
                                updated_at TIMESTAMPTZ,
                                created_by VARCHAR(255),
                                updated_by VARCHAR(255),

    -- Foreign keys
                                CONSTRAINT fk_task_assignees_task
                                    FOREIGN KEY (task_id)
                                        REFERENCES tasks(id),

                                CONSTRAINT fk_task_assignees_user
                                    FOREIGN KEY (user_id)
                                        REFERENCES users(id),

    -- Prevent duplicate assignments
                                CONSTRAINT uk_task_assignee
                                    UNIQUE (task_id, user_id)
);


-- ============================================
-- Indexes for frequently queried foreign keys
-- ============================================

CREATE INDEX idx_tasks_project_id
    ON tasks(project_id);

CREATE INDEX idx_tasks_creator
    ON tasks(creator);

CREATE INDEX idx_task_assignees_user_id
    ON task_assignees(user_id);
